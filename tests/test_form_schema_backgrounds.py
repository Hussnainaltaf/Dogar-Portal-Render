"""Every declared background image must exist on disk.

WHY THIS FILE EXISTS
--------------------
An external audit of the v1.1.0 release ZIP flagged:

    One document template references a missing background image
    -- permission_undertaking uses permission_undertaking_1.jpg, but that file
       is not present in app/static/pdf_backgrounds/
    -- that template can render without its intended background, breaking the
       visual PDF output for that form
    Status: not auto-patched because there is no safe way to infer the intended
    replacement image from the archive alone.

Declining to guess a replacement was right, but the premise was wrong: there is
no artwork to find. ``init_db.py``'s ``TEMPLATE_DEFS`` allow-list deliberately
excludes permission/undertaking letters -- "NOT coordinate templates ... they are
generated by the letterhead renderer" -- and
``app/services/letterhead_renderer.py`` produces them in HTML on the company
letterhead via ``render_demand_permission_request()`` / ``render_undertaking()``.
The filename was a leftover from before that redesign, so it was removed rather
than replaced, and the schema now states the real behaviour.

What made it survive a release is that ``_resolve_background_path()`` returned
``None`` for an unresolvable name without logging, so a template could silently
render as blank paper with text floating on it. That is now a warning, and this
test stops any new dangling reference from being introduced -- in either
direction: the seeded ``TEMPLATE_DEFS`` and the ``FORM_SCHEMAS`` catalogue are
both checked against the shipped directory.
"""
from __future__ import annotations

from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
BG_DIR = REPO_ROOT / "app" / "static" / "pdf_backgrounds"

# Minimum plausible size -- _resolve_background_path() rejects anything <= 200
# bytes, so a placeholder/truncated file must fail here too rather than pass the
# existence check and then be refused at render time.
MIN_BYTES = 200


def _leaf(name: str) -> str:
    """Backgrounds are stored either bare or as '/static/pdf_backgrounds/x.jpg'."""
    return name.replace("\\", "/").rsplit("/", 1)[-1]


def test_background_directory_is_present_and_populated():
    assert BG_DIR.is_dir(), f"missing backgrounds directory: {BG_DIR}"
    images = [p for p in BG_DIR.iterdir() if p.suffix.lower() in {".jpg", ".jpeg", ".png"}]
    assert images, (
        f"{BG_DIR} contains no images -- every overlay template would render as "
        "blank paper"
    )


def test_every_form_schema_background_exists():
    """The audit finding, generalised to the whole catalogue."""
    from app.services.form_schema import _RAW as FORM_SCHEMAS

    missing = {}
    for key, schema in FORM_SCHEMAS.items():
        bg = (schema.get("background_image") or "").strip()
        if not bg:
            continue  # explicitly no artwork (e.g. letterhead-rendered documents)
        path = BG_DIR / _leaf(bg)
        if not path.exists():
            missing[key] = bg
        elif path.stat().st_size <= MIN_BYTES:
            missing[key] = f"{bg} (only {path.stat().st_size} bytes)"

    assert not missing, (
        "form schema(s) declare background images that are not shipped: "
        f"{missing}. _resolve_background_path() returns None for these, so the "
        "document renders with no background artwork. Either add the file to "
        f"{BG_DIR} or set background_image to \"\" if the document is produced by "
        "the letterhead renderer instead."
    )


def test_every_seeded_template_background_exists():
    """The DB seed list is the other source of background references."""
    from app.db.init_db import TEMPLATE_DEFS

    missing = {}
    for row in TEMPLATE_DEFS:
        name, bg = row[0], (row[4] or "").strip()
        if not bg:
            continue
        path = BG_DIR / _leaf(bg)
        if not path.exists() or path.stat().st_size <= MIN_BYTES:
            missing[name] = bg

    assert not missing, (
        f"seeded template(s) reference missing background artwork: {missing}. "
        "Fresh installs would generate these documents on blank paper."
    )


def test_permission_undertaking_declares_no_overlay_background():
    """Pin the specific correction so the dangling name cannot be reinstated.

    If someone genuinely adds a permission-undertaking scan later, this test is
    the right place to fail: it forces a deliberate decision about whether the
    document should move back to the coordinate engine, rather than half-wiring
    an image into a schema whose output is produced by the letterhead renderer.
    """
    from app.services.form_schema import _RAW as FORM_SCHEMAS

    schema = FORM_SCHEMAS.get("permission_undertaking")
    if schema is None:
        pytest.skip("permission_undertaking schema was removed entirely")
    assert not (schema.get("background_image") or "").strip(), (
        "permission_undertaking declares an overlay background again. This "
        "document is rendered by app/services/letterhead_renderer.py "
        "(render_demand_permission_request / render_undertaking) and is excluded "
        "from init_db.TEMPLATE_DEFS on purpose, so an overlay background here "
        "would be drawn by nothing."
    )


def test_unresolvable_background_is_logged(tmp_path):
    """Silence was the actual defect -- prove the warning fires."""
    import logging

    from app.services import pdf_engine

    records: list[str] = []

    class _Collect(logging.Handler):
        def emit(self, record):  # noqa: D102
            records.append(record.getMessage())

    logger = logging.getLogger("dtc.pdf_engine")
    handler = _Collect(level=logging.WARNING)
    logger.addHandler(handler)
    prev = logger.level
    logger.setLevel(logging.WARNING)
    pdf_engine._MISSING_BG_WARNED.discard("does_not_exist_probe.jpg")

    class _Tpl:
        id = 999
        background_image = "does_not_exist_probe.jpg"

    try:
        result = pdf_engine._resolve_background_path(_Tpl())
    finally:
        logger.removeHandler(handler)
        logger.setLevel(prev)
        pdf_engine._MISSING_BG_WARNED.discard("does_not_exist_probe.jpg")

    assert result is None, "a missing background must not resolve to a path"
    assert any("does_not_exist_probe.jpg" in m for m in records), (
        "an unresolvable background produced no warning; a template rendering "
        "without its artwork would again be discoverable only by eye"
    )


def test_empty_background_does_not_warn():
    """A document with deliberately no artwork must stay quiet.

    Otherwise the letterhead-rendered documents would spam the log and train
    operators to ignore this warning -- which is how the original silence
    effectively existed in the first place.
    """
    import logging

    from app.services import pdf_engine

    records: list[str] = []

    class _Collect(logging.Handler):
        def emit(self, record):  # noqa: D102
            records.append(record.getMessage())

    logger = logging.getLogger("dtc.pdf_engine")
    handler = _Collect(level=logging.WARNING)
    logger.addHandler(handler)
    logger.setLevel(logging.WARNING)

    class _Tpl:
        id = 998
        background_image = ""

    try:
        assert pdf_engine._resolve_background_path(_Tpl()) is None
    finally:
        logger.removeHandler(handler)

    assert not records, f"empty background should not warn, got: {records}"
